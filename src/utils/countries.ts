/**
 * Get a country name from its ISO code
 * @param {string} code - The ISO code of the country
 * @returns {string} - The name of the country, or "Desconocido" if not found
 */
export const getCountryNameByCode = (code) => {
  if (!code) return "Desconocido";
  const country = COUNTRIES.find(
    (country) => country.code === code.toUpperCase(),
  );
  return country ? country.name : "Desconocido";
};

/**
 * Get a country code from its name
 * @param {string} name - The name of the country
 * @returns {string} - The ISO code of the country, or null if not found
 */
export const getCountryCodeByName = (name) => {
  if (!name) return null;
  const country = COUNTRIES.find(
    (country) => country.name.toLowerCase() === name.toLowerCase(),
  );
  return country ? country.code : null;
};

/**
 * Get all country names for dropdown options
 * @returns {Array<string>} - Array of country names
 */
export const getCountryNames = () => {
  return COUNTRIES.map((country) => country.name);
};

/**
 * Get all countries as options for select dropdowns
 * @returns {Array<Object>} - Array of objects with value and label properties
 */
export const getCountryOptions = () => {
  return COUNTRIES.map((country) => ({
    value: country.code,
    label: country.name,
  }));
};

